"""Measure in-process scoring latency of the serving code on a real snapshot.

This is a *local* benchmark: it runs the scoring service in this process with the in-memory
feature store, so it measures model loading, decoding, prediction, calibration and reason codes,
but not the network, API Gateway, Lambda start-up or DynamoDB. Lambda figures are measured after
deployment and recorded separately.

Usage:
    uv run python scripts/benchmark_scoring.py [--dataset HI-Small] [--requests 2000]
"""

from __future__ import annotations

import argparse
import statistics
import time
from datetime import datetime
from pathlib import Path

import numpy as np
import yaml

from muletrace.config import CONFIG_DIR, load_config
from muletrace.data.labels import LabelConfig
from muletrace.features.build import build_snapshots
from muletrace.features.config import FeatureConfig
from muletrace.models.artifact import load_artifact
from muletrace.perf import peak_memory_mb
from muletrace.serialization import to_builtin
from muletrace.serving.batch import feature_items
from muletrace.serving.feature_client import InMemoryFeatureStore
from muletrace.serving.handler import ScoringService

OUTPUT = Path("docs/generated/serving_benchmark.yaml")
AS_OF = datetime(2022, 9, 9)


def _percentile(samples: list[float], q: float) -> float:
    return round(float(np.percentile(samples, q)), 3)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--dataset", default="HI-Small")
    parser.add_argument("--requests", type=int, default=2000)
    args = parser.parse_args()

    labels = load_config(LabelConfig, CONFIG_DIR / "labels.yaml")
    features = load_config(FeatureConfig, CONFIG_DIR / "features.yaml")
    snapshot = build_snapshots(
        Path("data/processed") / args.dataset, Path("artifacts/features"), [AS_OF], labels, features
    )
    model_dir = Path("artifacts/models") / args.dataset

    started = time.perf_counter()
    artifact = load_artifact(model_dir)
    load_ms = (time.perf_counter() - started) * 1000

    store = InMemoryFeatureStore()
    store.put_many(feature_items(snapshot, artifact.features, args.dataset))
    service = ScoringService(artifact, store, args.dataset, probability_cap=0.99)
    accounts = snapshot["account_id"].to_list()
    rng = np.random.default_rng(0)
    chosen = rng.choice(len(accounts), size=args.requests, replace=True)

    service.score(accounts[0], AS_OF.date().isoformat())  # warm-up
    latencies = []
    for index in chosen:
        tick = time.perf_counter()
        service.score(accounts[int(index)], AS_OF.date().isoformat())
        latencies.append((time.perf_counter() - tick) * 1000)

    model_bytes = sum(path.stat().st_size for path in model_dir.iterdir())
    result = {
        "scope": "local, in-process: excludes network, API Gateway, Lambda start-up and DynamoDB",
        "dataset": args.dataset,
        "as_of": AS_OF.date().isoformat(),
        "requests": args.requests,
        "artifact_bytes": model_bytes,
        "artifact_load_ms": round(load_ms, 1),
        "latency_ms": {
            "p50": _percentile(latencies, 50),
            "p95": _percentile(latencies, 95),
            "p99": _percentile(latencies, 99),
            "mean": round(statistics.fmean(latencies), 3),
        },
        "peak_memory_mib": round(peak_memory_mb(), 0),
    }
    header = "# Generated by `scripts/benchmark_scoring.py`. Do not edit by hand.\n"
    OUTPUT.write_text(
        header + yaml.safe_dump(to_builtin(result), sort_keys=False),
        encoding="utf-8",
        newline="\n",
    )
    print(yaml.safe_dump(to_builtin(result), sort_keys=False))


if __name__ == "__main__":
    main()
