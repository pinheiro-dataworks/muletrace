"""Helpers shared by every command group."""

from __future__ import annotations

import argparse
import logging
from collections.abc import Callable
from pathlib import Path
from typing import Any, Final

import yaml

from muletrace.data.amlworld_loader import DATASETS
from muletrace.serialization import to_builtin
from muletrace.settings import Settings

logger = logging.getLogger("muletrace")

Handler = Callable[[argparse.Namespace, Settings], int]
Groups = Any  # argparse's private _SubParsersAction type

# AMLworld's documented primary period for the Small datasets is 1-10 September 2022.
PRIMARY_PERIOD_END: Final = "2022-09-11"
GENERATED_DIR: Final = Path("docs/generated")


def write_generated(file_name: str, content: dict[str, Any], command: str) -> None:
    """Write a generated YAML report under ``docs/generated`` with a provenance header."""
    output = GENERATED_DIR / file_name
    output.parent.mkdir(parents=True, exist_ok=True)
    header = f"# Generated by `{command}`. Do not edit by hand.\n"
    text = yaml.safe_dump(to_builtin(content), sort_keys=False)
    output.write_text(header + text, encoding="utf-8", newline="\n")
    logger.info("Wrote %s", output)


def add_command(
    commands: Groups,
    name: str,
    handler: Handler,
    help_text: str,
    datasets: list[str] | None = None,
) -> argparse.ArgumentParser:
    """Register a command that takes ``--datasets`` (all datasets unless given)."""
    command: argparse.ArgumentParser = commands.add_parser(name, help=help_text)
    command.add_argument(
        "--datasets", nargs="+", default=datasets or list(DATASETS), choices=DATASETS
    )
    command.set_defaults(handler=handler)
    return command
