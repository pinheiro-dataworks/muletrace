"""Command-line entry point: ``muletrace <group> <command>``.

Each command is a thin adapter from arguments to a library function, so everything the CLI
does can also be called from tests, notebooks and the SageMaker job.
"""

from __future__ import annotations

import argparse
import logging
from collections.abc import Callable, Sequence
from datetime import UTC, datetime
from pathlib import Path
from typing import TYPE_CHECKING, Any

import yaml

from muletrace.data.amlworld_loader import DATASETS, RawDataset
from muletrace.perf import measure
from muletrace.serialization import to_builtin
from muletrace.settings import Settings, load_env_file

if TYPE_CHECKING:
    from muletrace.models.experiment import ExperimentConfig

logger = logging.getLogger("muletrace")

Handler = Callable[[argparse.Namespace, Settings], int]

# AMLworld's documented primary period for the Small datasets is 1-10 September 2022.
PRIMARY_PERIOD_END = "2022-09-11"
GENERATED_DIR = Path("docs/generated")


def _write_generated(file_name: str, content: dict[str, Any], command: str) -> None:
    """Write a generated YAML report under ``docs/generated`` with a provenance header."""
    output = GENERATED_DIR / file_name
    output.parent.mkdir(parents=True, exist_ok=True)
    header = f"# Generated by `{command}`. Do not edit by hand.\n"
    text = yaml.safe_dump(to_builtin(content), sort_keys=False)
    output.write_text(header + text, encoding="utf-8")
    logger.info("Wrote %s", output)


def _raw_datasets(args: argparse.Namespace, settings: Settings) -> list[RawDataset]:
    return [RawDataset(name, settings.raw_dir) for name in args.datasets]


def _data_download(args: argparse.Namespace, settings: Settings) -> int:
    from muletrace.data.download import download_missing  # noqa: PLC0415 - keeps CLI start fast

    downloaded = download_missing(_raw_datasets(args, settings))
    logger.info("Downloaded %d file(s).", len(downloaded))
    return 0


def _data_manifest(args: argparse.Namespace, settings: Settings) -> int:
    from muletrace.data.manifest import write_manifest  # noqa: PLC0415

    files = [path for dataset in _raw_datasets(args, settings) for path in dataset.files]
    write_manifest(files, settings.manifest_path, generated_on=datetime.now(tz=UTC).date())
    logger.info("Wrote %s for %d file(s).", settings.manifest_path, len(files))
    return 0


def _data_verify(_: argparse.Namespace, settings: Settings) -> int:
    from muletrace.data.manifest import verify_manifest  # noqa: PLC0415

    verified = verify_manifest(settings.manifest_path, settings.raw_dir)
    logger.info("Checksums match for %d file(s).", len(verified))
    return 0


def _data_prepare(args: argparse.Namespace, settings: Settings) -> int:
    from muletrace.data.prepare import prepare_dataset  # noqa: PLC0415

    for raw in _raw_datasets(args, settings):
        prepare_dataset(raw, settings.processed_dir)
    return 0


def _data_simulate_pix(args: argparse.Namespace, settings: Settings) -> int:
    from muletrace.config import CONFIG_DIR, load_config  # noqa: PLC0415
    from muletrace.data import pix_layer_simulator  # noqa: PLC0415
    from muletrace.data.labels import LabelConfig  # noqa: PLC0415

    config = load_config(pix_layer_simulator.SimulatorConfig, CONFIG_DIR / "simulator.yaml")
    labels = load_config(LabelConfig, CONFIG_DIR / "labels.yaml")
    reports = {}
    for name in args.datasets:
        layer = pix_layer_simulator.run(settings.processed_dir / name, config, labels)
        logger.info("%s Pix layer: %s", name, layer.calibration["counts"])
        reports[name] = layer.calibration
    _write_generated("pix_layer_calibration.yaml", reports, "muletrace data simulate-pix")
    return 0


def _data_profile(args: argparse.Namespace, settings: Settings) -> int:
    from muletrace.data.profile import dataset_profile  # noqa: PLC0415

    profiles = {
        name: dataset_profile(settings.processed_dir / name, primary_end=PRIMARY_PERIOD_END)
        for name in args.datasets
    }
    _write_generated("data_profile.yaml", profiles, "muletrace data profile")
    return 0


def _models_rules(args: argparse.Namespace, settings: Settings) -> int:
    from muletrace.config import CONFIG_DIR, load_config  # noqa: PLC0415
    from muletrace.data.labels import LabelConfig  # noqa: PLC0415
    from muletrace.models.evaluate import EvaluationConfig  # noqa: PLC0415
    from muletrace.models.rules_baseline import RulesConfig, evaluate_rules  # noqa: PLC0415

    labels = load_config(LabelConfig, CONFIG_DIR / "labels.yaml")
    rules = load_config(RulesConfig, CONFIG_DIR / "rules.yaml")
    evaluation = load_config(EvaluationConfig, CONFIG_DIR / "evaluation.yaml")
    results = {
        name: evaluate_rules(settings.processed_dir / name, labels, rules, evaluation)
        for name in args.datasets
    }
    _write_generated("rules_baseline.yaml", results, "muletrace models rules")
    return 0


def _features_build(args: argparse.Namespace, settings: Settings) -> int:
    from muletrace.config import CONFIG_DIR, load_config  # noqa: PLC0415
    from muletrace.data.labels import LabelConfig  # noqa: PLC0415
    from muletrace.features.asof import snapshot_times  # noqa: PLC0415
    from muletrace.features.build import build_snapshots  # noqa: PLC0415
    from muletrace.features.config import FeatureConfig  # noqa: PLC0415
    from muletrace.models.evaluate import EvaluationConfig  # noqa: PLC0415

    labels = load_config(LabelConfig, CONFIG_DIR / "labels.yaml")
    features = load_config(FeatureConfig, CONFIG_DIR / "features.yaml")
    evaluation = load_config(EvaluationConfig, CONFIG_DIR / "evaluation.yaml")
    times = snapshot_times(
        evaluation.first_snapshot, evaluation.last_snapshot, evaluation.snapshot_step
    )
    for name in args.datasets:
        snapshots = build_snapshots(
            settings.processed_dir / name, settings.features_dir, times, labels, features
        )
        logger.info("%s: %d snapshot rows", name, snapshots.height)
    return 0


def _experiment_config() -> ExperimentConfig:
    from muletrace.config import CONFIG_DIR, load_config  # noqa: PLC0415
    from muletrace.data.labels import LabelConfig  # noqa: PLC0415
    from muletrace.features.config import FeatureConfig  # noqa: PLC0415
    from muletrace.models.evaluate import EvaluationConfig  # noqa: PLC0415
    from muletrace.models.experiment import ExperimentConfig  # noqa: PLC0415
    from muletrace.models.rules_baseline import RulesConfig  # noqa: PLC0415
    from muletrace.models.train import TrainingConfig  # noqa: PLC0415

    return ExperimentConfig(
        labels=load_config(LabelConfig, CONFIG_DIR / "labels.yaml"),
        features=load_config(FeatureConfig, CONFIG_DIR / "features.yaml"),
        rules=load_config(RulesConfig, CONFIG_DIR / "rules.yaml"),
        training=load_config(TrainingConfig, CONFIG_DIR / "training.yaml"),
        evaluation=load_config(EvaluationConfig, CONFIG_DIR / "evaluation.yaml"),
    )


def _models_backtest(args: argparse.Namespace, settings: Settings) -> int:
    from muletrace.models.experiment import run_experiment  # noqa: PLC0415

    config = _experiment_config()
    for name in args.datasets:
        result = run_experiment(settings.processed_dir / name, settings.artifacts_dir, config)
        _write_generated(f"backtest_{name}.yaml", result, "muletrace models backtest")
    return 0


def _models_delay_sweep(args: argparse.Namespace, settings: Settings) -> int:
    from muletrace.models.experiment import run_delay_sweep  # noqa: PLC0415

    config = _experiment_config()
    for name in args.datasets:
        backtest = yaml.safe_load((GENERATED_DIR / f"backtest_{name}.yaml").read_text("utf-8"))
        result = run_delay_sweep(
            settings.processed_dir / name,
            settings.artifacts_dir,
            config,
            tuple(args.delays),
            backtest["chosen_params"],
        )
        _write_generated(f"delay_sweep_{name}.yaml", result, "muletrace models delay-sweep")
    return 0


def build_parser() -> argparse.ArgumentParser:
    """Build the argument parser with every command group."""
    parser = argparse.ArgumentParser(prog="muletrace", description=__doc__)
    groups = parser.add_subparsers(dest="group", required=True)

    data = groups.add_parser("data", help="Download, verify and prepare AMLworld")
    data_commands = data.add_subparsers(dest="command", required=True)
    for name, handler, help_text in (
        ("download", _data_download, "Download missing raw files from Kaggle"),
        ("manifest", _data_manifest, "Write data/MANIFEST.yaml from the raw files"),
        ("verify", _data_verify, "Check raw files against data/MANIFEST.yaml"),
        ("prepare", _data_prepare, "Convert raw files to validated Parquet tables"),
        ("simulate-pix", _data_simulate_pix, "Add the seeded Pix layer to prepared data"),
        ("profile", _data_profile, "Write headline statistics to docs/generated"),
    ):
        command = data_commands.add_parser(name, help=help_text)
        command.add_argument("--datasets", nargs="+", default=list(DATASETS), choices=DATASETS)
        command.set_defaults(handler=handler)

    models = groups.add_parser("models", help="Baselines, training and evaluation")
    model_commands = models.add_subparsers(dest="command", required=True)
    rules = model_commands.add_parser("rules", help="Score the rules baseline on the hold-out")
    rules.add_argument("--datasets", nargs="+", default=list(DATASETS), choices=DATASETS)
    rules.set_defaults(handler=_models_rules)
    backtest = model_commands.add_parser("backtest", help="Run the model ladder backtest")
    backtest.add_argument("--datasets", nargs="+", default=list(DATASETS), choices=DATASETS)
    backtest.set_defaults(handler=_models_backtest)
    sweep = model_commands.add_parser("delay-sweep", help="Label-delay sensitivity on the hold-out")
    sweep.add_argument("--datasets", nargs="+", default=["HI-Small"], choices=DATASETS)
    sweep.add_argument("--delays", nargs="+", type=int, default=[0, 12, 24, 48, 72])
    sweep.set_defaults(handler=_models_delay_sweep)

    feature_group = groups.add_parser("features", help="Point-in-time feature snapshots")
    feature_commands = feature_group.add_subparsers(dest="command", required=True)
    build = feature_commands.add_parser("build", help="Build and cache every snapshot")
    build.add_argument("--datasets", nargs="+", default=list(DATASETS), choices=DATASETS)
    build.set_defaults(handler=_features_build)
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    """Parse arguments, configure logging and run the selected command."""
    load_env_file()
    logging.basicConfig(
        level=logging.INFO, format="%(asctime)s %(levelname)s %(name)s: %(message)s"
    )
    args = build_parser().parse_args(argv)
    handler: Handler = args.handler
    with measure() as measurement:
        status = handler(args, Settings.from_env())
    logger.info(
        "%s %s finished in %.1f s, peak memory %.0f MiB",
        args.group,
        args.command,
        measurement.seconds,
        measurement.peak_memory_mb,
    )
    return status


if __name__ == "__main__":
    raise SystemExit(main())
